"""Independent sanity checks for the m0-basic fixture's report.

`tests/test_cli_e2e.py` compares the CLI's output against the checked-in
`expected-report.json` golden file -- but that file was generated by the
same implementation under test, so a bug reproduced at generation time would
reproduce silently at comparison time too. This file makes direct,
hand-written assertions about known fixture facts (values a human can read
straight out of `fixtures/m0-basic/{call.pcap,agent-trace.json}` without
running any VoiceWire code) so correctness does not rest on the golden file
alone.
"""

import json

from voicewire.core.analyze import AnalysisInputs, run_analysis
from voicewire.models.clock import AlignmentType
from voicewire.models.capture_context import VantagePointKind
from voicewire.models.correlation import CorrelationMethod


def _run(pcap_path, trace_path, capture_context_path=None):
    return run_analysis(
        AnalysisInputs(pcap_path=pcap_path, trace_path=trace_path, capture_context_path=capture_context_path)
    )


def test_expected_sip_call_id(pcap_path, trace_path, capture_context_path):
    report = _run(pcap_path, trace_path, capture_context_path)

    sip_events = [e for e in report.evidence_events if e.kind == "sip.message"]
    call_ids = {e.attributes["call_id"] for e in sip_events}
    assert call_ids == {"voicewire-m0@example.test"}


def test_expected_sip_event_count_and_methods(pcap_path, trace_path, capture_context_path):
    report = _run(pcap_path, trace_path, capture_context_path)

    sip_events = [e for e in report.evidence_events if e.kind == "sip.message"]
    assert len(sip_events) == 5

    seen = sorted(
        e.attributes.get("method") or f"status:{e.attributes.get('status_code')}" for e in sip_events
    )
    assert seen == ["ACK", "BYE", "INVITE", "status:200", "status:200"]


def test_expected_rtp_stream_evidence(pcap_path, trace_path, capture_context_path):
    report = _run(pcap_path, trace_path, capture_context_path)

    rtp_events = [e for e in report.evidence_events if e.kind == "rtp.packet"]
    assert len(rtp_events) == 5

    ssrcs = {e.attributes["ssrc"] for e in rtp_events}
    assert ssrcs == {"0xcafebabe"}

    seqs = sorted(e.attributes["sequence_number"] for e in rtp_events)
    assert seqs == [1000, 1001, 1002, 1003, 1004]

    payload_types = {e.attributes["payload_type"] for e in rtp_events}
    assert payload_types == {0}


def test_trace_event_identity_and_type_preservation(pcap_path, trace_path, capture_context_path):
    report = _run(pcap_path, trace_path, capture_context_path)

    trace_events = {e.source.locator: e for e in report.evidence_events if e.kind.startswith("trace.")}
    assert set(trace_events) == {"event:evt-1", "event:evt-2", "event:evt-3"}
    assert trace_events["event:evt-1"].kind == "trace.vad.speech_end"
    assert trace_events["event:evt-2"].kind == "trace.first_audio"
    assert trace_events["event:evt-3"].kind == "trace.agent.turn_end"


def test_ambiguous_trace_semantics_remain_ambiguous(pcap_path, trace_path, capture_context_path):
    """`first_audio` is deliberately ambiguous in the source trace. It must
    reach the report unchanged -- never promoted to a more specific claim
    like `tts_first_audio_received` or `caller_first_audio_received`."""
    report = _run(pcap_path, trace_path, capture_context_path)

    first_audio = next(e for e in report.evidence_events if e.source.locator == "event:evt-2")
    assert first_audio.kind == "trace.first_audio"
    assert "tts" not in first_audio.kind
    assert "caller" not in first_audio.kind
    assert "received" not in first_audio.kind


def test_provenance_frame_and_event_ids_present(pcap_path, trace_path, capture_context_path):
    report = _run(pcap_path, trace_path, capture_context_path)

    pcap_locators = {
        e.source.locator for e in report.evidence_events if e.source.adapter == "tshark"
    }
    assert pcap_locators == {f"frame:{n}" for n in range(1, 11)}  # 10 packets in call.pcap

    trace_locators = {
        e.source.locator for e in report.evidence_events if e.source.adapter == "trace_fixture"
    }
    assert trace_locators == {"event:evt-1", "event:evt-2", "event:evt-3"}


def test_expected_rtp_to_sip_correlation(pcap_path, trace_path, capture_context_path):
    report = _run(pcap_path, trace_path, capture_context_path)

    media_correlations = [c for c in report.correlations if c.kind == "sdp_media_to_rtp_stream"]
    assert len(media_correlations) == 1
    correlation = media_correlations[0]
    assert correlation.method == CorrelationMethod.exact_sdp_endpoint_match
    assert correlation.left_ref == "sip:call_id:voicewire-m0@example.test"
    assert correlation.right_ref == "rtp:stream:0xcafebabe"

    rtp_ids = {e.id for e in report.evidence_events if e.kind == "rtp.packet"}
    sip_ids_with_sdp = {
        e.id
        for e in report.evidence_events
        if e.kind == "sip.message" and "sdp_media_port" in e.attributes
    }
    assert rtp_ids.issubset(set(correlation.supporting_evidence_ids))
    assert sip_ids_with_sdp.issubset(set(correlation.supporting_evidence_ids))


def test_expected_trace_to_sip_dialog_correlation(pcap_path, trace_path, capture_context_path):
    report = _run(pcap_path, trace_path, capture_context_path)

    dialog_correlations = [c for c in report.correlations if c.kind == "trace_call_to_sip_dialog"]
    assert len(dialog_correlations) == 1
    assert dialog_correlations[0].method == CorrelationMethod.exact_sip_call_id_match
    assert len(dialog_correlations[0].supporting_evidence_ids) == 5  # all 5 SIP messages share the Call-ID


def test_exact_alignment_only_when_explicitly_declared(pcap_path, trace_path, capture_context_path):
    report = _run(pcap_path, trace_path, capture_context_path)

    alignment = report.clock_alignments[0]
    assert alignment.type == AlignmentType.exact
    assert alignment.declared_by is not None  # traceable to the trace's own clock.alignment_to_capture_clock


def test_unresolved_alignment_without_declaration(pcap_path, capture_context_path, tmp_path):
    trace_without_alignment = {
        "call": {"sip_call_id": "voicewire-m0@example.test"},
        "clock": {"id": "fixture-clock", "type": "wall"},
        "events": [],
    }
    trace_path = tmp_path / "trace-no-alignment.json"
    trace_path.write_text(json.dumps(trace_without_alignment), encoding="utf-8")

    report = _run(pcap_path, trace_path, capture_context_path)

    alignment = report.clock_alignments[0]
    assert alignment.type == AlignmentType.unresolved
    assert alignment.declared_by is None
    assert alignment.offset_seconds is None


def test_capture_vantage_independently_known(pcap_path, trace_path, capture_context_path):
    report = _run(pcap_path, trace_path, capture_context_path)
    assert report.capture_context.vantage_point_kind == VantagePointKind.agent_host
    assert report.capture_context.supplied_by.method == "fixture_manifest"


def test_capture_vantage_independently_unspecified(pcap_path, trace_path):
    report = _run(pcap_path, trace_path, capture_context_path=None)
    assert report.capture_context.vantage_point_kind == VantagePointKind.unspecified
    assert report.capture_context.supplied_by.method == "unspecified"
